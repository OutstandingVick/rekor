import type { SolveResult } from "dbc-curve-sim";
import type { Design } from "./design";

/**
 * A standalone script that creates this exact config on devnet with the Meteora
 * SDK — the same approach apps/devnet-spike used, where the program accepted
 * the curve unchanged and live fills matched to the atom.
 */
export function initScript(design: Design, solved: SolveResult): string {
  const supply = BigInt(Math.round(design.supplyTokens)) * 10n ** BigInt(design.baseDecimals);
  const points = solved.config.curve
    .map((p) => `  { sqrtPrice: new BN("${p.sqrtPrice}"), liquidity: new BN("${p.liquidity}") },`)
    .join("\n");
  return `// Generated by Rekor. Creates this curve's DBC config on devnet.
// npm i @meteora-ag/dynamic-bonding-curve-sdk@1.5.13 @solana/web3.js @solana/spl-token bn.js
// Run: KEYPAIR=~/.config/solana/devnet.json npx tsx init-config.ts
import { readFileSync } from "node:fs";
import { DynamicBondingCurveClient, buildCurve } from "@meteora-ag/dynamic-bonding-curve-sdk";
import { NATIVE_MINT } from "@solana/spl-token";
import { Connection, Keypair, sendAndConfirmTransaction } from "@solana/web3.js";
import BN from "bn.js";

const connection = new Connection("https://api.devnet.solana.com", "confirmed");
const payer = Keypair.fromSecretKey(Uint8Array.from(JSON.parse(readFileSync(process.env.KEYPAIR!, "utf8"))));

// Designed curve: exact program values. Do not round.
const sqrtStartPrice = new BN("${solved.config.sqrtStartPrice}");
const curve = [
${points}
];
const migrationQuoteThreshold = new BN("${solved.config.migrationQuoteThreshold}"); // lamports
const totalSupply = new BN("${supply}"); // atoms, ${design.baseDecimals} decimals

// Fees, migration and LP split from the SDK's own builder so they are valid by construction.
const template = buildCurve({
  token: { tokenType: 0, tokenBaseDecimal: ${design.baseDecimals}, tokenQuoteDecimal: 9, tokenAuthorityOption: 0, totalTokenSupply: 1_000_000_000, leftover: 0 },
  fee: {
    baseFeeParams: { baseFeeMode: 0, feeSchedulerParam: { startingFeeBps: ${design.feeBps}, endingFeeBps: ${design.feeBps}, numberOfPeriod: 0, totalDuration: 0 } },
    dynamicFeeEnabled: false,
    collectFeeMode: 0,
    creatorTradingFeePercentage: ${design.creatorPct},
    poolCreationFee: 0,
    enableFirstSwapWithMinFee: false,
  },
  migration: { migrationOption: 1, migrationFeeOption: 0, migrationFee: { feePercentage: 0, creatorFeePercentage: 0 } },
  liquidityDistribution: { partnerPermanentLockedLiquidityPercentage: 100, partnerLiquidityPercentage: 0, creatorPermanentLockedLiquidityPercentage: 0, creatorLiquidityPercentage: 0 },
  lockedVesting: { totalLockedVestingAmount: 0, numberOfVestingPeriod: 0, cliffUnlockAmount: 0, totalVestingDuration: 0, cliffDurationFromMigrationTime: 0 },
  activationType: 0,
  percentageSupplyOnMigration: 20,
  migrationQuoteThreshold: 85,
} as any);

const config = Keypair.generate();
const client = DynamicBondingCurveClient.create(connection, "confirmed");
const tx = await client.partner.createConfig({
  ...template,
  sqrtStartPrice,
  curve,
  migrationQuoteThreshold,
  tokenSupply: { preMigrationTokenSupply: totalSupply, postMigrationTokenSupply: totalSupply },
  config: config.publicKey,
  feeClaimer: payer.publicKey,
  leftoverReceiver: payer.publicKey,
  quoteMint: NATIVE_MINT,
  payer: payer.publicKey,
});
const sig = await sendAndConfirmTransaction(connection, tx, [payer, config]);
console.log("config", config.publicKey.toBase58(), sig);
`;
}
